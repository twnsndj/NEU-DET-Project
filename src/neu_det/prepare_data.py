"""Build data/yolo/ from raw NEU-DET: validate, convert, split, write.

Run from the repo root:  uv run python -m neu_det.prepare_data
"""
from __future__ import annotations

import shutil
from pathlib import Path

from neu_det.check_data import check
from neu_det.convert import CLASSES, to_yolo_lines
from neu_det.split import stratified_split

OUT = Path("data/yolo")
SPLITS_DIR = Path("splits")
CONFIG = Path("configs/data.yaml")


def load_all(pairs: dict[str, tuple[Path, Path]]) -> tuple[dict[str, tuple[Path, list[str]]], list[str]]:
    """Convert every pair in memory. Returns ({stem: (image_path, label_lines)}, errors)."""
    data: dict[str, tuple[Path, list[str]]] = {}
    errors: list[str] = []
    for stem, (img, xml) in pairs.items():
        try:
            data[stem] = (img, to_yolo_lines(xml, img))
        except ValueError as e:
            errors.append(str(e))
    return data, errors


def _write_lines(path: Path, lines: list[str]) -> None:
    """One item per line, trailing newline, LF endings on every OS."""
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def write_splits(splits: dict[str, list[str]]) -> None:
    """Write splits/{train,val,test}.txt: the committed record of the split."""
    SPLITS_DIR.mkdir(exist_ok=True)
    for name, stems in splits.items():
        _write_lines(SPLITS_DIR / f"{name}.txt", stems)


def build_yolo_dir(splits: dict[str, list[str]], data: dict[str, tuple[Path, list[str]]]) -> None:
    """Delete and rebuild data/yolo/images/<split>/ and data/yolo/labels/<split>/."""
    # Guard: never rmtree anything outside data/.
    if OUT.resolve().parent != Path("data").resolve():
        raise RuntimeError(f"refusing to delete {OUT.resolve()}")
    if OUT.exists():
        shutil.rmtree(OUT)

    for split, stems in splits.items():
        img_dir = OUT / "images" / split
        lbl_dir = OUT / "labels" / split
        img_dir.mkdir(parents=True)
        lbl_dir.mkdir(parents=True)
        for stem in stems:
            img, lines = data[stem]
            shutil.copy2(img, img_dir / img.name)
            _write_lines(lbl_dir / f"{stem}.txt", lines)


def write_data_yaml() -> None:
    """Generate configs/data.yaml from CLASSES (the single source of class order)."""
    CONFIG.parent.mkdir(exist_ok=True)
    lines = [
        "# Generated by neu_det.prepare_data. Do not edit by hand.",
        f"path: {OUT.resolve().as_posix()}",
        "train: images/train",
        "val: images/val",
        "test: images/test",
        "names:",
        *(f"  {i}: {name}" for i, name in enumerate(CLASSES)),
    ]
    _write_lines(CONFIG, lines)


def main() -> int:
    # 1. READ + VALIDATE: nothing is written until every file passes.
    report = check()
    if report.images_only or report.xmls_only or report.duplicates:
        print("Issues found in the data:")
        if report.images_only:
            print(f"  Images without corresponding XML files: {report.images_only}")
        if report.xmls_only:
            print(f"  XML files without corresponding images: {report.xmls_only}")
        if report.duplicates:
            print(f"  Duplicate entries: {report.duplicates}")
        return 1
    data, errors = load_all(report.pairs)
    for error in errors:
        print(f"Error processing file: {error}")
    if errors:
        return 1
    n_boxes = sum(len(lines) for _, lines in data.values())
    print(f"validated {len(data)} images, {n_boxes} boxes, 0 errors")

    # 2. DECIDE
    splits = stratified_split([img for img, _ in data.values()])
    print("split: " + "  ".join(f"{name} {len(stems)}" for name, stems in splits.items()))

    # 3. WRITE
    write_splits(splits)
    build_yolo_dir(splits, data)
    write_data_yaml()
    print(f"wrote {SPLITS_DIR}/, {OUT}/, {CONFIG}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
